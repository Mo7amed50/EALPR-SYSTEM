"""Phase 2 / Block B — thumbnail generation and on-disk cache.

Design constraints honoured here:

* Thumbnails are a **derived, disposable cache on disk**, never a new database
  field. The 60 legacy records whose images live in MongoDB ``BinaryField``
  keep their bytes untouched; this module only *reads* them.
* Nothing here raises. A missing, truncated, corrupt or unsupported image
  returns ``None`` so the caller can fall back without a 500 page.
* The cache is keyed by detection id + image type + size. Detection images are
  immutable once written, so a cached thumbnail cannot go stale. If the cache
  directory is deleted the next request simply rebuilds it.
"""
import io
import os
import tempfile
from pathlib import Path

from config import THUMBNAIL_DIR, THUMBNAIL_QUALITY, THUMBNAIL_SIZE

# Magic-byte signatures. Used instead of trusting a filename or a hardcoded
# "image/jpeg", so a PNG or WEBP served from disk is labelled correctly.
_IMAGE_SIGNATURES = (
    (b"\xff\xd8\xff", "image/jpeg"),
    (b"\x89PNG\r\n\x1a\n", "image/png"),
    (b"GIF87a", "image/gif"),
    (b"GIF89a", "image/gif"),
    (b"BM", "image/bmp"),
    (b"II*\x00", "image/tiff"),
    (b"MM\x00*", "image/tiff"),
)

FALLBACK_MIME = "application/octet-stream"


def sniff_image_mime(head: bytes):
    """Return the MIME type implied by the file's magic bytes, or None."""
    if not head:
        return None
    for signature, mime in _IMAGE_SIGNATURES:
        if head.startswith(signature):
            return mime
    # RIFF containers are WebP in practice; anything else is not an image here.
    if head.startswith(b"RIFF") and head[8:12] == b"WEBP":
        return "image/webp"
    return None


def extension_for_mime(mime: str) -> str:
    return {
        "image/jpeg": ".jpg",
        "image/png": ".png",
        "image/gif": ".gif",
        "image/bmp": ".bmp",
        "image/tiff": ".tiff",
        "image/webp": ".webp",
    }.get(mime, ".bin")


def thumbnail_cache_path(detection_id, img_type, size=None) -> Path:
    """Deterministic cache location for one thumbnail."""
    size = size or THUMBNAIL_SIZE
    safe_id = "".join(ch for ch in str(detection_id) if ch.isalnum())
    return Path(THUMBNAIL_DIR) / f"{safe_id}_{img_type}_{size[0]}x{size[1]}.jpg"


def read_cached_thumbnail(cache_path: Path):
    """Return cached thumbnail bytes, or None if there is no usable cache entry."""
    try:
        if cache_path.is_file():
            data = cache_path.read_bytes()
            if data:
                return data
    except OSError:
        return None
    return None


def build_thumbnail(source, size=None, quality=None) -> bytes:
    """Decode `source` (bytes or a path) and return a resized JPEG.

    Raises on unusable input; callers use :func:`get_or_create_thumbnail`,
    which converts failures into ``None``.
    """
    from PIL import Image, ImageOps

    size = size or THUMBNAIL_SIZE
    quality = quality or THUMBNAIL_QUALITY

    if isinstance(source, (bytes, bytearray)):
        handle = io.BytesIO(bytes(source))
    else:
        handle = str(source)

    with Image.open(handle) as image:
        # Honour EXIF orientation so portrait phone photos are not rotated.
        image = ImageOps.exif_transpose(image) or image
        # Flatten transparency/palette modes so JPEG encoding cannot fail.
        if image.mode not in ("RGB", "L"):
            image = image.convert("RGB")
        elif image.mode == "L":
            image = image.convert("RGB")
        # thumbnail() never enlarges and preserves the aspect ratio.
        image.thumbnail(size, Image.LANCZOS)
        output = io.BytesIO()
        image.save(output, format="JPEG", quality=quality, optimize=True)
        return output.getvalue()


def _write_atomically(cache_path: Path, data: bytes) -> bool:
    """Write via a temp file + replace so a crash cannot leave a partial file."""
    temp_name = None
    try:
        cache_path.parent.mkdir(parents=True, exist_ok=True)
        handle = tempfile.NamedTemporaryFile(
            dir=str(cache_path.parent), suffix=".tmp", delete=False)
        temp_name = handle.name
        try:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        finally:
            handle.close()
        os.replace(temp_name, str(cache_path))
        return True
    except OSError:
        # A read-only or full disk must not break image delivery: the caller
        # still receives the freshly generated bytes, just uncached.
        return False
    finally:
        # If the replace never happened, do not leave a stray .tmp behind.
        if temp_name is not None and os.path.exists(temp_name):
            try:
                os.unlink(temp_name)
            except OSError:
                pass


def get_or_create_thumbnail(source, detection_id, img_type, size=None) -> bytes:
    """Return thumbnail bytes, generating and caching them at most once.

    Returns ``None`` when the source is missing, corrupt, or in a format this
    build of Pillow cannot decode. Never raises.
    """
    # The cache is consulted *before* the source is validated or loaded: a hit
    # must be answerable without touching MongoDB or the source file at all.
    size = size or THUMBNAIL_SIZE
    cache_path = thumbnail_cache_path(detection_id, img_type, size)

    cached = read_cached_thumbnail(cache_path)
    if cached is not None:
        return cached

    if not source:
        return None
    try:
        data = build_thumbnail(source, size=size)
    except Exception:
        # Unreadable, truncated, or unsupported image. The caller falls back.
        return None

    _write_atomically(cache_path, data)
    return data


def thumbnail_cache_stats():
    """Small helper for diagnostics and tests."""
    path = Path(THUMBNAIL_DIR)
    try:
        files = [f for f in path.iterdir() if f.is_file()]
    except OSError:
        return {"exists": path.is_dir(), "count": 0, "bytes": 0}
    return {
        "exists": True,
        "count": len(files),
        "bytes": sum(f.stat().st_size for f in files),
    }
